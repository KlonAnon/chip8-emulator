#pragma once
#include <cstdint>

struct Chip8
{
    uint8_t memory[4096];
    uint8_t V[16];
    uint16_t I = 0;
    uint16_t pc = 0x200;
    uint16_t stack[16];
    uint8_t sp = 0;
    uint8_t delayTimer = 0;
    uint8_t soundTimer = 0;
    bool display[64 * 32];
    bool keys[16];

    // Variables needed to track key status for Fx0A instruction
    bool waitingForKeyRelease = false;
    uint8_t waitingKey = 0;

    // Needed to check if last executed opcode was a draw instruction
    bool draw_exec;

    const uint8_t FONT_START = 0x0000;
    const uint8_t FONTSET[80] = {
        0xF0, 0x90, 0x90, 0x90, 0xF0, // 0
        0x20, 0x60, 0x20, 0x20, 0x70, // 1
        0xF0, 0x10, 0xF0, 0x80, 0xF0, // 2
        0xF0, 0x10, 0xF0, 0x10, 0xF0, // 3
        0x90, 0x90, 0xF0, 0x10, 0x10, // 4
        0xF0, 0x80, 0xF0, 0x10, 0xF0, // 5
        0xF0, 0x80, 0xF0, 0x90, 0xF0, // 6
        0xF0, 0x10, 0x20, 0x40, 0x40, // 7
        0xF0, 0x90, 0xF0, 0x90, 0xF0, // 8
        0xF0, 0x90, 0xF0, 0x10, 0xF0, // 9
        0xF0, 0x90, 0xF0, 0x90, 0x90, // A
        0xE0, 0x90, 0xE0, 0x90, 0xE0, // B
        0xF0, 0x80, 0x80, 0x80, 0xF0, // C
        0xE0, 0x90, 0x90, 0x90, 0xE0, // D
        0xF0, 0x80, 0xF0, 0x80, 0xF0, // E
        0xF0, 0x80, 0xF0, 0x80, 0x80  // F
    };

    void reset();
    bool loadRom(const char *filename);
    void cycle();
};